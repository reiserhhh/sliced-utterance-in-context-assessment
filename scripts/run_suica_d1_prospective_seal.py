LEAK_WHITELIST = {"4.238555648405859", "2.6977587972014083"}


def report_leak_check(predictions: dict, report_text: str) -> dict[str, Any]:
    """G2D sub-gate: no prediction-bearing value may appear in the COMMITTED
    report, except the two published L2 edges disclosed in Part 0.2."""
    found: list[dict[str, Any]] = []
    n_checked = 0

    def walk(o: Any, key: str | None = None) -> None:
        nonlocal n_checked
        if isinstance(o, dict):
            for k, v in o.items():
                walk(v, k)
        elif isinstance(o, list):
            for v in o:
                walk(v, key)
        elif isinstance(o, bool):
            return
        elif isinstance(o, (int, float)) and key in PREDICTION_BEARING_KEYS:
            n_checked += 1
            s = repr(o)
            if len(s) >= 6 and s in report_text and s not in LEAK_WHITELIST:
                found.append({"key": key, "rendering": s})

    walk(predictions)
    return {"n_prediction_bearing_values_checked": n_checked,
            "n_leaks": len(found), "leaks": found,
            "whitelisted": sorted(LEAK_WHITELIST), "clean": not found}


def _numbers(obj: Any) -> list[float]:
    out: list[float] = []
    if isinstance(obj, dict):
        for v in obj.values():
            out += _numbers(v)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            out += _numbers(v)
    elif isinstance(obj, bool):
        pass
    elif isinstance(obj, (int, float)):
        out.append(float(obj))
    return out


