# The five entries.  PREDICTION ARITHMETIC ONLY.

def _phi_lower_tail(z: float) -> float:
    """Phi(-z) = 0.5 erfc(z/sqrt(2)) -- l2:415's own expression, verbatim."""
    return 0.5 * math.erfc(z / math.sqrt(2.0))


def sigma_u2(eta: float, sigma_b2: float, k_tau: int, m: int) -> float:
    """Appendix R.1 / L2 derivation 2, l2:392-394 and l2:934-936:
        sigma_u^2(eta) = eta sigma_b^2/k_tau + (1-eta) sigma_b^2/m."""
    return eta * sigma_b2 / k_tau + (1.0 - eta) * sigma_b2 / m


def s1_band_constant(w3: dict[str, Any]) -> dict[str, Any]:
    """RN-D1-6: S-1's relative band = S1_BAND_SAFETY x (the MAX observed
    relative deviation of measured-from-predicted over L2's ten-cell W-3
    containment record, restricted to cells whose PREDICTED rate is at least
    S1_FLOOR_PRED_MIN -- the regime S-1's non-degenerate entries live in;
    the sub-1e-6 cells are numerically degenerate and get an ABSOLUTE band)."""
    meas, pred = w3["measured"], w3["predicted"]
    devs = {}
    for cell, p in pred.items():
        if p >= S1_FLOOR_PRED_MIN:
            devs[cell] = abs(meas[cell] - p) / p
    worst_cell = max(devs, key=devs.get)
    return {"per_cell_relative_deviation": devs,
            "worst_cell": worst_cell, "max_relative_deviation": devs[worst_cell],
            "safety_factor": S1_BAND_SAFETY,
            "relative_band": S1_BAND_SAFETY * devs[worst_cell],
            "absolute_band_for_degenerate_cells": S1_ZERO_ABS_BAND,
            "n_cells_used": len(devs), "n_cells_total": len(pred)}


def entry_s1(v: dict[str, float], band: dict[str, Any]) -> dict[str, Any]:
    """S-1: the eta-floor curve at m=96, k_tau=4, G=5, n_occ=8, rho.55-eq."""
    m, k_tau = S1_CONFIG["m"], S1_CONFIG["k_tau"]
    delta, sb2 = v["delta_L1"], v["sigma_b2_rho55eq"]
    primary = {}
    for eta in S1_CONFIG["eta_levels"]:
        su2 = sigma_u2(eta, sb2, k_tau, m)
        z = delta / (2.0 * math.sqrt(su2))
        rate = _phi_lower_tail(z)
        if rate >= S1_FLOOR_PRED_MIN:
            b = {"kind": "relative", "band": band["relative_band"],
                 "lo": rate * (1.0 - band["relative_band"]),
                 "hi": rate * (1.0 + band["relative_band"])}
        elif rate <= S1_ZERO_PRED_MAX:
            b = {"kind": "absolute", "band": S1_ZERO_ABS_BAND,
                 "lo": 0.0, "hi": S1_ZERO_ABS_BAND}
        else:
            b = {"kind": "relative(intermediate)", "band": band["relative_band"],
                 "lo": rate * (1.0 - band["relative_band"]),
                 "hi": rate * (1.0 + band["relative_band"])}
        primary[f"eta{eta:g}"] = {"sigma_u2": su2, "boundary_z": z,
                                  "predicted_per_boundary_rate": rate,
                                  "falsification_band": b}
    # RN-D1-4 companion: the Delta-FREE rho-parameterized form made INTERNALLY
    # consistent with G=5's own regular-simplex constant c_G = (G-1)/(2G).
    g = S1_CONFIG["G"]
    c_g = (g - 1) / (2.0 * g)
    rho = 0.55
    companion = {}
    for eta in S1_CONFIG["eta_levels"]:
        # z(eta) = (Delta/2) / sigma_u(eta), sigma_b^2 = c_G Delta^2 rho/(1-rho)
        inv_dims = eta / k_tau + (1.0 - eta) / m
        z = 1.0 / (2.0 * math.sqrt(c_g * rho / (1.0 - rho) * inv_dims))
        companion[f"eta{eta:g}"] = {"boundary_z": z,
                                    "predicted_per_boundary_rate":
                                        _phi_lower_tail(z)}
    return {
        "id": "S-1",
        "title": "eta-floor curve at an unrun config",
        "grade": "MEASURED-LAW",
        "config": dict(S1_CONFIG),
        "formula": ("per-boundary rate = Phi(-Delta/(2 sigma_u(eta))), "
                    "sigma_u^2(eta) = eta sigma_b^2/k_tau + (1-eta) sigma_b^2/m"),
        "formula_source": ("scripts/run_suica_m4_l2_threshold_continuum.py:"
                           "384-416 (predicted_boundary_error_l2 docstring's "
                           "LATENT reduction, l2:391-393) and l2:934-936; "
                           "IDT appendix R.1 / Q.1"),
        "constants": {"Delta": delta, "sigma_b2": sb2},
        "primary": primary,
        "companion_delta_free_G5_consistent": companion,
        "band_rule": band,
    }


