def _suica_caller() -> str | None:
    """The IMMEDIATE caller of the RNG entry point, and only if it is a SUICA
    file.  Attributing to the immediate frame (not the first non-library frame
    below it) is what separates SUICA's own randomness from a third-party
    library's: `scipy.stats` calls `default_rng` while building distribution
    docstrings, and a first-non-library walk would blame whichever SUICA line
    happened to `import scipy.stats`."""
    stack = inspect.stack()
    if len(stack) < 3:
        return None
    fr = stack[2]
    f = fr.filename
    if str(ROOT) in f and "/site-packages/" not in f \
            and Path(f).name != Path(__file__).name:
        return f"{Path(f).parent.name}/{Path(f).name}:{fr.lineno}"
    FOREIGN_RNG["n"] += 1
    return None


