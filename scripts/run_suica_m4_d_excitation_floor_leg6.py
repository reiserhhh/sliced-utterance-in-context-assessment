_PANEL_FIELDS = (
    "response",
    "menu",
    "generated_menu",
    "external_menu",
    "choice",
    "history",
    "duration",
    "environment",
)


def _amplitude0_identity_gate(
    context: dict[str, Any],
    spec: M4ChartEcologySpec,
) -> dict[str, Any]:
    excited0 = build_excited_observed(
        context["observed"],
        context["truth"],
        spec,
        seed=context["seed"],
        amplitude=0.0,
    )
    mismatches = []
    for view in ("train", "test"):
        for role in ("calibration", "selection"):
            natural = getattr(context["observed"].ecology, f"{view}_{role}")
            rebuilt = getattr(excited0.ecology, f"{view}_{role}")
            for field in _PANEL_FIELDS:
                if not np.array_equal(
                    getattr(natural, field), getattr(rebuilt, field)
                ):
                    mismatches.append(f"{view}_{role}.{field}")
    if mismatches:
        raise RuntimeError(
            "amplitude-0 pipeline identity gate FAILED on "
            f"{context['world']} rep {context['repetition']}: the excitation "
            "generator does not reproduce the natural panels on the same "
            f"RNG streams; mismatched fields: {mismatches}"
        )
    return {
        "world": context["world"],
        "repetition": context["repetition"],
        "fields_checked": len(_PANEL_FIELDS) * 4,
        "identity_holds": True,
    }


