def _excited_budget_rows_for_world_rep(
    context: dict[str, Any],
    *,
    spec: M4ChartEcologySpec,
    budgets: tuple[float, ...],
    excited_1x: Any,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Leg-4b budget rows with C3.3-excited calibration/selection panels.

    Mirrors leg4._budget_rows_for_world_rep row-for-row (same forced routes,
    same references, same degenerate rule) with the panels swapped for
    build_excited_observed output at each budget. The 1x excited observed is
    passed in so the stacking arm consumes the identical object.
    """
    world = context["world"]
    repetition = context["repetition"]
    seed = context["seed"]
    truth = context["truth"]
    v2_basis = context["v2_basis"]
    oracle_basis = truth.oracle_basis
    hazard_ridge = context["fit_kwargs"]["hazard_ridge"]
    iterations = context["fit_kwargs"]["logistic_iterations"]
    dimensions = context["flat"][("train", 0)][0]["response_next"].shape[1]
    true_d = {
        author: leg4._true_derivative(truth, author)
        for author in range(context["authors"])
    }
    rows: list[dict[str, Any]] = []
    scales: list[dict[str, Any]] = []
    for budget in budgets:
        events_b = int(round(spec.events * budget))
        if budget == 1.0:
            excited_b = excited_1x
            spec_b = spec
        else:
            spec_b = replace(spec, events=events_b)
            observed_b, truth_b = generate_m4_chart_ecology_world(
                world=world,
                spec=spec_b,
                seed=seed,
            )
            for role in ("calibration", "selection", "evaluation"):
                if not np.array_equal(
                    truth_b.oracle_basis[role], oracle_basis[role]
                ):
                    raise RuntimeError(
                        f"frozen-world violation at budget {budget}: oracle "
                        f"basis[{role}] changed on {world} rep {repetition}"
                    )
            for name in ("creation", "gate", "generated_base", "selection"):
                if not np.array_equal(
                    truth_b.author_parameters[name],
                    truth.author_parameters[name],
                ):
                    raise RuntimeError(
                        f"frozen-world violation at budget {budget}: author "
                        f"parameter {name} changed on {world} rep {repetition}"
                    )
            excited_b = build_excited_observed(
                observed_b,
                truth_b,
                spec_b,
                seed=seed,
                amplitude=AMPLITUDE,
            )
        scale = excited_b.ecology.design["response_excitation_scale"]
        scales.append(
            {
                "world": world,
                "repetition": repetition,
                "budget": budget,
                "events": events_b,
                "scale_0": float(scale[0]),
                "scale_1": float(scale[1]),
                "amplitude": AMPLITUDE,
            }
        )
        for view in ("train", "test"):
            calibration_panel = getattr(
                excited_b.ecology, f"{view}_calibration"
            )
            selection_panel = getattr(excited_b.ecology, f"{view}_selection")
            for author in range(context["authors"]):
                oracle_stack = context["oracle_stacks"][view][author]
                forced_route = oracle_stack["selected_model"]
                d_orc_1x = oracle_stack["D"]
                d_norm_orc_1x = float(np.linalg.norm(d_orc_1x))
                keys = {
                    "world": world,
                    "repetition": repetition,
                    "seed": seed,
                    "author": author,
                    "view": view,
                    "budget": budget,
                    "events": events_b,
                    "forced_route": forced_route,
                }
                if d_norm_orc_1x < leg4.FLIP_TOLERANCE:
                    rows.append(
                        {
                            **keys,
                            "degenerate_reference": True,
                            "e_d_paired": np.nan,
                            "e_d_frozen": np.nan,
                            "e_d_true": np.nan,
                            "e_orc_true": np.nan,
                            "orc_self_drift": np.nan,
                            "reference_gap": np.nan,
                            "d_norm_disc_b": np.nan,
                            "d_norm_orc_b": np.nan,
                            "d_norm_orc_1x": d_norm_orc_1x,
                            "d_norm_true": float(
                                np.linalg.norm(true_d[author])
                            ),
                        }
                    )
                    continue
                calibration = _flatten_events(calibration_panel, author)
                selection = _flatten_events(selection_panel, author)
                d_disc = leg4._forced_route_derivative(
                    calibration,
                    selection,
                    v2_basis,
                    model=forced_route,
                    hazard_ridge=hazard_ridge,
                    logistic_iterations=iterations,
                    dimensions=dimensions,
                )
                d_orc = leg4._forced_route_derivative(
                    calibration,
                    selection,
                    oracle_basis,
                    model=forced_route,
                    hazard_ridge=hazard_ridge,
                    logistic_iterations=iterations,
                    dimensions=dimensions,
                )
                d_true = true_d[author]
                rows.append(
                    {
                        **keys,
                        "degenerate_reference": False,
                        "e_d_paired": leg3._relative_error(d_disc, d_orc),
                        "e_d_frozen": leg3._relative_error(d_disc, d_orc_1x),
                        "e_d_true": leg3._relative_error(d_disc, d_true),
                        "e_orc_true": leg3._relative_error(d_orc, d_true),
                        "orc_self_drift": leg3._relative_error(
                            d_orc, d_orc_1x
                        ),
                        "reference_gap": leg3._relative_error(
                            d_orc_1x, d_true
                        ),
                        "d_norm_disc_b": float(np.linalg.norm(d_disc)),
                        "d_norm_orc_b": float(np.linalg.norm(d_orc)),
                        "d_norm_orc_1x": d_norm_orc_1x,
                        "d_norm_true": float(np.linalg.norm(d_true)),
                    }
                )
    return rows, scales


# ---------------------------------------------------------------------------
# stacking arm -- two-stage + excitation at 1x
# ---------------------------------------------------------------------------


def _stacking_rows_for_world_rep(
    context: dict[str, Any],
    excited_1x: Any,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    """arm0_excited / stage1_excited / two_stage_excited vs natural oracle."""
    keys_base = {
        "world": context["world"],
        "repetition": context["repetition"],
        "seed": context["seed"],
    }
    exc_flat: dict[tuple[str, int], tuple[dict, dict, dict]] = {}
    exc_base: dict[str, list[dict[str, Any]]] = {"train": [], "test": []}
    for view in ("train", "test"):
        calibration_panel = getattr(excited_1x.ecology, f"{view}_calibration")
        selection_panel = getattr(excited_1x.ecology, f"{view}_selection")
        for author in range(context["authors"]):
            natural_eval = context["flat"][(view, author)][2]
            events = (
                _flatten_events(calibration_panel, author),
                _flatten_events(selection_panel, author),
                natural_eval,
            )
            exc_flat[(view, author)] = events
            exc_base[view].append(
                leg3._fit_v2_stack(
                    *events,
                    context["v2_basis"],
                    **context["fit_kwargs"],
                    query_masks=context["query_masks"],
                )
            )
    exc_context = {**context, "base_stacks": exc_base, "flat": exc_flat}
    stage1_stacks = leg4._arm2_stacks_for_lambda(exc_context, STAGE1_LAMBDA)
    two_stage_stacks: dict[str, list[dict[str, Any]]] = {
        "train": [],
        "test": [],
    }
    fresh_refits = 0
    for view in ("train", "test"):
        for author in range(context["authors"]):
            stack, fresh = leg5._two_stage_stack(
                exc_context, view, author, stage1_stacks[view][author]
            )
            two_stage_stacks[view].append(stack)
            if fresh:
                fresh_refits += 1
    arm_stacks = {
        "arm0_excited": exc_base,
        "stage1_excited": stage1_stacks,
        "two_stage_excited": two_stage_stacks,
    }
    loop_rows: list[dict[str, Any]] = []
    world_rows: list[dict[str, Any]] = []
    for arm in STACKING_ARMS:
        arm_rows = [
            leg3._loop_row(
                {**keys_base, "author": author, "view": view},
                arm,
                arm_stacks[arm][view][author],
                context["oracle_stacks"][view][author],
            )
            for view in ("train", "test")
            for author in range(context["authors"])
        ]
        loop_rows.extend(arm_rows)
        geometries = leg3._arm_geometries(
            arm_stacks[arm], context["oracle_stacks"]
        )
        world_rows.append(
            {
                **keys_base,
                "arm": arm,
                "chart_family": context["chart"].selected_family,
                "arm_lambda": (
                    STAGE1_LAMBDA if arm == "stage1_excited" else np.nan
                ),
                **geometries,
                "flips": int(sum(row["model_flip"] for row in arm_rows)),
                "route_mismatches": int(
                    sum(row["route_mismatch"] for row in arm_rows)
                ),
                "mean_e_loop": float(
                    np.mean([row["e_loop"] for row in arm_rows])
                ),
                "mean_e_d": float(
                    np.mean([row["e_d_atom"] for row in arm_rows])
                ),
            }
        )
    structure = {**keys_base, "fresh_stage2_refits": fresh_refits}
    return loop_rows, world_rows, structure


