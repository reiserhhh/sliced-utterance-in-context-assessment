def _assert_passive_rows(
    rows: list[dict[str, Any]],
    stored: pd.DataFrame,
    world: str,
    repetition: int,
) -> dict[str, Any]:
    mine = pd.DataFrame(rows)
    reference = stored[
        (stored["world"] == world) & (stored["repetition"] == repetition)
    ]
    keys = ["world", "repetition", "author", "view", "budget"]
    merged = reference.merge(mine, on=keys, suffixes=("_leg4", "_leg6"))
    if len(merged) != len(mine) or len(merged) != len(reference):
        raise RuntimeError(
            f"passive rows misaligned with Leg 4 on {world} rep "
            f"{repetition}: {len(merged)} matches vs mine {len(mine)} / "
            f"stored {len(reference)}"
        )
    checks: dict[str, Any] = {
        "world": world,
        "repetition": repetition,
        "rows_compared": int(len(merged)),
    }
    flags_equal = bool(
        (
            merged["degenerate_reference_leg4"]
            == merged["degenerate_reference_leg6"]
        ).all()
        and (merged["forced_route_leg4"] == merged["forced_route_leg6"]).all()
        and (merged["events_leg4"] == merged["events_leg6"]).all()
    )
    checks["flags_equal"] = flags_equal
    usable = merged[~merged["degenerate_reference_leg4"]]
    max_diff = 0.0
    for name in FLOOR_METRICS:
        diff = float(
            np.max(np.abs(usable[f"{name}_leg4"] - usable[f"{name}_leg6"]))
        )
        checks[f"max_abs_{name}_difference"] = diff
        max_diff = max(max_diff, diff)
    checks["max_abs_difference"] = max_diff
    if max_diff > ROW_TOLERANCE or not flags_equal:
        raise RuntimeError(
            f"passive floor replay diverges from Leg 4 persisted rows on "
            f"{world} rep {repetition}: max|diff|={max_diff:.3e} "
            f"flags_equal={flags_equal}"
        )
    return checks


