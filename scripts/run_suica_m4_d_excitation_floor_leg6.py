# startup gate -- probe design sanity (mirrors C3.3's frozen test)
# ---------------------------------------------------------------------------


def _probe_design_gate() -> dict[str, float]:
    probes = np.stack(
        [balanced_response_probe(index, np.ones(2)) for index in range(4)]
    )
    mean_abs = float(np.max(np.abs(np.mean(probes, axis=0))))
    gram_gap = float(np.max(np.abs(probes.T @ probes - 2.0 * np.eye(2))))
    if mean_abs > 1e-12 or gram_gap > 1e-12:
        raise RuntimeError(
            f"balanced probe design gate failed: mean_abs={mean_abs:.3e} "
            f"gram_gap={gram_gap:.3e}"
        )
    return {"probe_mean_abs": mean_abs, "probe_gram_gap": gram_gap}


